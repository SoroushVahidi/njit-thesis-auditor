"""Regression tests for R019/P019 Ester-review evidence rendering
(scripts/ester_batch/lib.py, docs/status/p019_r019_esther_evidence_pdf_fix_20260831.md).

Background: the R019 combined review PDF's per-document evidence was
generated by `scripts/ester_batch/build_rule_package.py::_fill_evidence` ->
`lib.build_evidence`, which returned an empty result (no rendered page at
all) for *any* finding with `page is None` -- true for every one of the
seven dissertations' weakest-surviving R019 finding (P019's document-wide
"mixed_numbering_style" check), per policy selection
(`lib.select_weakest_finding`, confidence-only, never page-based). Esther
could not review the R019 PDF because it carried no dissertation evidence at
all, just a generic text panel per student.

`pdf_page_numbers.py` was separately extended (see
tests/test_p019_location_evidence.py) to attach the already-detected
candidate geometry for the transition boundary responsible
(`transition_prev_page`/`transition_prev_bbox`/... and
`transition_new_page`/`transition_new_bbox`/...) to that same finding,
purely additively. This file covers the evidence-rendering half: consuming
that geometry to render two real, highlighted dissertation pages instead of
nothing, while leaving every other page-less finding (all 59 other
applicable rules) exactly as before.
"""

from __future__ import annotations

import sys
from pathlib import Path

import fitz

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts" / "ester_batch"))

from lib import build_evidence  # noqa: E402

_PAGE_W = 612.0
_PAGE_H = 792.0
_BOTTOM_CENTER_X = 296.0
_BOTTOM_Y = 765.0


def _add_bottom_center_number(page: fitz.Page, text: str) -> None:
    page.insert_text((_BOTTOM_CENTER_X, _BOTTOM_Y), text, fontsize=12.0)


def _build_transition_doc(tmp_path: Path) -> Path:
    """A small synthetic dissertation with a suspicious numbering-style jump."""
    doc = fitz.open()
    for value in ("i", "ii", "iii"):
        page = doc.new_page(width=_PAGE_W, height=_PAGE_H)
        _add_bottom_center_number(page, value)
    for value in ("7", "8"):
        page = doc.new_page(width=_PAGE_W, height=_PAGE_H)
        _add_bottom_center_number(page, value)
    path = tmp_path / "transition_doc.pdf"
    doc.save(path)
    doc.close()
    return path


def _real_document_level_details(pdf_path: Path) -> dict[str, str]:
    """Run the real P019 detector and return the document-wide finding's
    own details dict, so tests exercise real, not hand-typed, geometry."""
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
    from njit_auditor.pdf_layout import load_pdf_layout
    from njit_auditor.rules.pdf_page_numbers import check_pdf_page_number_sequence

    model = load_pdf_layout(str(pdf_path))
    findings = check_pdf_page_number_sequence(model)
    doc_level = [
        f
        for f in findings
        if f.page is None and f.details.get("issue_type") == "mixed_numbering_style"
    ]
    assert doc_level, "fixture must produce a document-wide mixed_numbering_style finding"
    return doc_level[0].details


# ---------------------------------------------------------------------------
# A document-level finding that DOES carry transition geometry renders real,
# highlighted, two-page evidence.
# ---------------------------------------------------------------------------


def test_document_level_transition_finding_renders_two_page_evidence(tmp_path: Path) -> None:
    pdf_path = _build_transition_doc(tmp_path)
    details = _real_document_level_details(pdf_path)
    out_path = tmp_path / "evidence.pdf"

    result = build_evidence(pdf_path, None, details, "P019", out_path)

    assert result.has_highlight is True
    assert result.transition_pages == [3, 4]
    assert result.transition_labels == ["iii", "7"]
    assert out_path.exists()

    with fitz.open(out_path) as evidence_doc:
        assert evidence_doc.page_count == 2
        first_text = evidence_doc[0].get_text("text")
        second_text = evidence_doc[1].get_text("text")
        assert "iii" in first_text
        assert "7" in second_text


def test_document_level_transition_evidence_highlights_are_visible(tmp_path: Path) -> None:
    """No blank placeholder-only evidence page: both rendered pages must
    carry a real highlight annotation, not just bare page content."""
    pdf_path = _build_transition_doc(tmp_path)
    details = _real_document_level_details(pdf_path)
    out_path = tmp_path / "evidence.pdf"

    build_evidence(pdf_path, None, details, "P019", out_path)

    with fitz.open(out_path) as evidence_doc:
        for page in evidence_doc:
            annots = list(page.annots()) if page.annots() else []
            drawings = page.get_drawings()
            assert annots or drawings, "expected a visible highlight on every evidence page"


def test_document_level_transition_evidence_location_names_both_pages(tmp_path: Path) -> None:
    pdf_path = _build_transition_doc(tmp_path)
    details = _real_document_level_details(pdf_path)
    out_path = tmp_path / "evidence.pdf"

    result = build_evidence(pdf_path, None, details, "P019", out_path)

    assert "page 3" in result.location.lower()
    assert "page 4" in result.location.lower()
    assert "iii" in result.location
    assert '"7"' in result.location


# ---------------------------------------------------------------------------
# Every other page-less finding (no transition_* fields in details) is
# completely unaffected -- same empty result as before this change.
# ---------------------------------------------------------------------------


def test_unrelated_page_less_finding_still_gets_empty_evidence(tmp_path: Path) -> None:
    """A page-less finding from any other rule (no transition_* detail
    fields at all) must fall back to exactly the prior behavior: no
    rendered page, empty result -- this change must not alter evidence
    rendering for the other 59 applicable rules' review PDFs."""
    pdf_path = _build_transition_doc(tmp_path)
    out_path = tmp_path / "evidence.pdf"

    result = build_evidence(
        pdf_path,
        None,
        {"issue_type": "some_other_document_level_issue", "confidence": "low"},
        "P999",
        out_path,
    )

    assert result.boxes == []
    assert result.location == ""
    assert result.affected_lines == []
    assert result.page_size is None
    assert result.has_highlight is False
    assert result.transition_pages is None
    assert result.transition_labels is None
    assert not out_path.exists()


def test_transition_evidence_ignored_when_only_one_side_present(tmp_path: Path) -> None:
    """A details dict naming only one side of the pair (malformed/partial)
    must not attempt a partial render -- falls back to the empty result."""
    pdf_path = _build_transition_doc(tmp_path)
    out_path = tmp_path / "evidence.pdf"

    result = build_evidence(
        pdf_path,
        None,
        {
            "issue_type": "mixed_numbering_style",
            "confidence": "low",
            "transition_prev_page": "3",
            "transition_prev_bbox": "270.0,753.0,320.0,765.0",
            # transition_new_page/transition_new_bbox intentionally absent.
        },
        "P019",
        out_path,
    )

    assert result.has_highlight is False
    assert not out_path.exists()


def test_ordinary_page_anchored_finding_unaffected(tmp_path: Path) -> None:
    """A normal, page-anchored finding (the common case for the other 59
    rules) is untouched by this change -- exercised via the real per-page
    P019 bbox path as a concrete example."""
    pdf_path = _build_transition_doc(tmp_path)
    out_path = tmp_path / "evidence.pdf"

    result = build_evidence(
        pdf_path,
        1,
        {"issue_type": "missing_page_number", "confidence": "medium"},
        "P019",
        out_path,
    )

    assert result.transition_pages is None
    assert result.transition_labels is None
    assert out_path.exists()
