"""Derive the complete rule/route inventory from the authoritative online code."""

from __future__ import annotations

import ast
import hashlib
import json
import subprocess
from pathlib import Path

from njit_auditor import web_app

ROOT = Path(__file__).resolve().parents[1]
BASELINE = "35ed4e01cf09cab9fafeb179a5cecaa71c0d736b"


def baseline(path: Path) -> bytes:
    return subprocess.check_output(["git", "show", f"{BASELINE}:{path.as_posix()}"], cwd=ROOT)


def main() -> None:
    rules_path = Path("data/processed/rules/project_added_rules.json")
    rules = json.loads(baseline(rules_path))
    assert (ROOT / rules_path).read_bytes() == baseline(rules_path)
    runner_path = Path("src/njit_auditor/audit_runner.py")
    assert (ROOT / runner_path).read_bytes() == baseline(runner_path)
    tree = ast.parse(baseline(runner_path))
    checks = sorted(
        {
            n.args[0].id
            for n in ast.walk(tree)
            if isinstance(n, ast.Call)
            and isinstance(n.func, ast.Name)
            and n.func.id == "run_check"
            and n.args
            and isinstance(n.args[0], ast.Name)
        }
    )
    modules = sorted((ROOT / "src/njit_auditor/rules").glob("*.py"))
    for module in modules:
        assert module.read_bytes() == baseline(module.relative_to(ROOT)), module
    lines = [
        "# Windows / intended website feature parity matrix",
        "",
        f"Intended website release source: `{BASELINE}`.",
        "Generated by `scripts/build_desktop_parity_matrix.py`; rerun to detect rule drift.",
        "",
        f"Catalog: **{len(rules)} rule records**. PDF runner: **{len(checks)} "
        f"registered check calls**.",
        f"All **{len(modules)} rule-module files**, the dispatcher and canonical catalog are",
        "byte-identical to the intended website source. No thresholds or experimental",
        "defaults changed.",
        "Every module is explicitly included in the frozen application. Source-only rules",
        "are retained in the package; both graphical interfaces accept PDF only.",
        "P082 remains opt-in/off by default; P084 is absent from the website catalog.",
        "",
        "Code identity proves implementation coverage, not that every branch has been",
        "exercised by synthetic fixtures or that a Windows installer passed qualification.",
        "",
        "| Rule ID | Description | Input / website applicability | Shared implementation |",
        "| --- | --- | --- | --- |",
    ]
    for rule in rules:
        description = str(rule.get("rule_definition") or rule.get("question", "")).replace("|", "/")
        description = " ".join(description.split())
        mode = web_app._input_label(rule)
        lines.append(f"| {rule['id']} | {description} | {mode} | Identical; bundled |")
    lines += [
        "",
        "## Executed PDF check inventory",
        "",
        *[f"- `{check}`" for check in checks],
        "",
        "## User-facing features",
        "",
        "| Online feature | Desktop equivalent | Verification |",
        "| --- | --- | --- |",
        "| PDF upload, validation and limit | Same handler and validation | Synthetic "
        "upload/rejection |",
        "| URL PDF import | Save PDF, then local upload; no network importer | Same "
        "saved bytes audited |",
        "| Built-in examples | Locally generated synthetic example | Same upload/audit pipeline |",
        "| Private online sample corpus | Not distributed | No student documents in bundle |",
        "| Grouped/topic/rule/page/issue findings | Shared routes and templates | JSON "
        "and drilldown comparison |",
        "| Filters, sort, explanations, correction text | Shared templates and "
        "reporting functions | Browser/source parity |",
        "| Original PDF | Shared PDF route | Byte comparison |",
        "| Full/single-page highlights and annotations | Shared generators | Text, "
        "drawings, annotation comparison |",
        "| JSON, Markdown, text, combined student PDF | Shared exports | Normalized "
        "content comparison |",
        "| Help and Rule Reference | Bundled templates, catalog and explanations | "
        "Reference-content comparison |",
        "| Contact email link | Opens configured email client; sending needs connectivity "
        "| Explicit user action |",
        "| Job polling and error recovery | Same status route; local process supervisor "
        "| Lifecycle tests |",
        "| Online server retention | Local delete/cancel/Quit cleanup | Lifecycle and "
        "packaged smoke |",
        "| Health/version APIs | Build provenance in package; no student health API | Inventory |",
        "| TeX, ZIP, DOCX | Not accepted by the website homepage or desktop | "
        "PDF-only rejection |",
        "",
        "## Intended website route inventory",
        "",
        "| Method | Route | Desktop mapping |",
        "| --- | --- | --- |",
    ]
    for route in web_app.app.routes:
        path = getattr(route, "path", "")
        if path in {"/healthz", "/version", "/openapi.json"}:
            mapping = "Hosted service metadata; not a local document feature"
        elif path == "/audits/url":
            mapping = "Save PDF locally and upload (no remote requests)"
        elif path == "/audits/sample":
            mapping = "Local synthetic example"
        else:
            mapping = "Same endpoint and implementation"
        lines.append(
            f"| {', '.join(sorted(getattr(route, 'methods', [])))} | `{path}` | {mapping} |"
        )
    lines += [
        "",
        "## Rule-module identity manifest",
        "",
        "| Module | SHA-256 (website target and desktop candidate) |",
        "| --- | --- |",
    ]
    for module in modules:
        lines.append(f"| `{module.name}` | `{hashlib.sha256(module.read_bytes()).hexdigest()}` |")
    (ROOT / "docs/WINDOWS_FEATURE_PARITY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rules)} rules; {len(checks)} PDF checks; {len(modules)} identical module files")


if __name__ == "__main__":
    main()
